// Admin Server Actions. Each one is a public POST endpoint, so each verifies the session cookie and
// the permission itself, reads only the fields it expects, and calls the same idempotent operation as the
// API (no HTTP call to /api/v1). The actor is always the signed-in user; no form field can name one.
//
// Every form carries a hidden idempotency key generated by the server when the page is rendered. A
// double-click or a browser resubmission sends the same key, so the operation runs once; after success the
// redirect renders a fresh form with a new key.

export type { FormState } from "./_lib/form";

export async function createProductAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireAdmin("catalog:write");
  let productId: string;
  try {
    const { value } = await createProductOnce(getDb(), principal, text(form, "idempotencyKey"), {
      slug: text(form, "slug"),
      nameEn: optional(form, "nameEn"),
      nameBn: optional(form, "nameBn"),
      descriptionEn: optional(form, "descriptionEn"),
      descriptionBn: optional(form, "descriptionBn"),
    });
    productId = value.id;
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/admin/products/${productId}?done=created`);
}

