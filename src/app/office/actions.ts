// Owner Office Server Actions. Each one is a public POST endpoint, so each verifies the session cookie and
// the permission itself, reads only the fields it expects, and calls the same idempotent operation as the
// API (no HTTP call to /api/v1). The actor is always the signed-in user; no form field can name one.
//
// Every form carries a hidden idempotency key generated by the server when the page is rendered. A
// double-click or a browser resubmission sends the same key, so the operation runs once; after success the
// redirect renders a fresh form with a new key.

/** An action's answer to its form: a safe message, and the submitted text so the form can show it again. */
export type FormState = { error?: string; values?: Record<string, string> };

const text = (form: FormData, name: string): string => {
  const value = form.get(name);
  return typeof value === "string" ? value : "";
};
const optional = (form: FormData, name: string): string | null => text(form, name).trim() || null;

function wholeNumber(raw: string, field: string, signed = false): number {
  if (!(signed ? /^-?[0-9]{1,10}$/ : /^[0-9]{1,10}$/).test(raw.trim())) {
    throw new DomainError("INVALID_INPUT", `${field} must be a whole number.`);
  }
  return Number(raw.trim());
}

/** Safe text for the form: a DomainError message is written to be shown; anything else is generic. */
function formError(error: unknown, form: FormData): FormState {
  const values: Record<string, string> = {};
  for (const [name, value] of form) if (typeof value === "string" && /^[a-zA-Z]+$/.test(name) && name !== "idempotencyKey") values[name] = value;
  if (error instanceof DomainError) {
    if (error.code === "IDEMPOTENCY_KEY_REUSED") {
      return { error: "This form was already submitted with different values. Reload the page to make a new entry.", values };
    }
    return { error: error.message, values };
  }
  console.error(
    JSON.stringify({
      level: "error",
      event: "office_action_failed",
      errorName: error instanceof Error ? error.name : typeof error,
      sqlState: pgErrorCode(error) ?? null,
    }),
  );
  return { error: "Something went wrong and nothing was saved. Please try again.", values };
}

export async function createProductAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireOffice("catalog:write");
  let productId: string;
  try {
    const { value } = await createProductOnce(getDb(), principal, text(form, "idempotencyKey"), {
      slug: text(form, "slug"),
      nameEn: optional(form, "nameEn"),
      nameBn: optional(form, "nameBn"),
      descriptionEn: optional(form, "descriptionEn"),
      descriptionBn: optional(form, "descriptionBn"),
    });
    productId = value.id;
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/office/products/${productId}?done=created`);
}

export async function createVariantAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireOffice("catalog:write");
  const productId = text(form, "productId");
  try {
    await createVariantOnce(getDb(), principal, text(form, "idempotencyKey"), {
      productId,
      sku: text(form, "sku"),
      size: optional(form, "size"),
      colour: optional(form, "colour"),
      pricePaisa: parseTakaToPaisa(text(form, "priceTaka")),
    });
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/office/products/${productId}?done=variant`);
}

export async function archiveProductAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireOffice("catalog:write");
  const productId = text(form, "productId");
  try {
    await archiveProductOnce(getDb(), principal, text(form, "idempotencyKey"), productId);
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/office/products/${productId}?done=archived`);
}

export async function deactivateVariantAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireOffice("catalog:write");
  let productId: string;
  try {
    const { value } = await deactivateVariantOnce(getDb(), principal, text(form, "idempotencyKey"), text(form, "variantId"));
    productId = value.productId;
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/office/products/${productId}?done=deactivated`);
}

export async function receiveStockAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireOffice("stock:receive");
  let sku: string;
  try {
    const { value } = await receiveStockOnce(getDb(), principal, text(form, "idempotencyKey"), {
      sku: text(form, "sku"),
      quantity: wholeNumber(text(form, "quantity"), "Quantity"),
      reason: optional(form, "reason"),
    });
    sku = value.sku;
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/office/skus/${encodeURIComponent(sku)}?done=received`);
}

export async function adjustStockAction(_: FormState, form: FormData): Promise<FormState> {
  const principal = await requireOffice("stock:adjust");
  let sku: string;
  try {
    const { value } = await adjustStockOnce(getDb(), principal, text(form, "idempotencyKey"), {
      sku: text(form, "sku"),
      quantityDelta: wholeNumber(text(form, "quantityDelta"), "Change", true),
      reason: text(form, "reason"),
    });
    sku = value.sku;
  } catch (error) {
    return formError(error, form);
  }
  redirect(`/office/skus/${encodeURIComponent(sku)}?done=adjusted`);
}
