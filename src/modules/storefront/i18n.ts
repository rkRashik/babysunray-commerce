const BANGLA = "০১২৩৪৫৬৭৮৯";
/** ASCII digits → Bangla digits (numbers only; no rounding). */
export function toBnDigits(value: number | string): string {
  return String(value).replace(/[0-9]/g, (d) => BANGLA[Number(d)]);
}

export const DICTIONARIES: Record<Lang, Dictionary> = { en, bn };
export const dictionary = (lang: Lang): Dictionary => DICTIONARIES[lang];

/**
 * Integer paisa → "৳ 1,250" or "৳ 1,250.50" (Bangla digits for "bn"). The taka and paisa parts are formatted
 * separately from the integer, so there is no floating point anywhere.
 */
export function formatTaka(paisa: number, lang: Lang): string {
  const sign = paisa < 0 ? "−" : "";
  const abs = Math.abs(paisa);
  const taka = Math.trunc(abs / 100);
  const rest = abs % 100;
  const grouped = new Intl.NumberFormat("en-IN").format(taka);
  const text = rest ? `${grouped}.${String(rest).padStart(2, "0")}` : grouped;
  return `${sign}৳ ${lang === "bn" ? toBnDigits(text) : text}`;
}

/** The product text in the chosen language, or null when that language was not written (no fallback text is invented). */
export const localised = (lang: Lang, en: string | null, bn: string | null) => (lang === "bn" ? bn : en);
